#!/bin/bash

# Builds "Story Engine.app" in the root of this folder: a copy of the
# Electron runtime from node_modules, renamed and given the Harpoon icon,
# that runs the editor from this folder in its own window. That gives the
# Story Engine its own name and icon in the Dock and the app switcher.
#
# The app isn't part of the repository (it's in .gitignore). This script
# runs after every npm install and from scripts/update.sh, and does
# nothing when the app is already up to date. It's re-signed locally
# ("ad hoc"), so no Apple Developer account is needed; it never leaves
# this Mac.

set -e
cd "$(dirname "$0")/.."

# Mac only, and not on CI
[ "$(uname)" = "Darwin" ] || exit 0
[ -z "$CI" ] || exit 0

APP_NAME="Story Engine"
BUNDLE_ID="productions.harpoon.story-engine"
SRC="node_modules/electron/dist/Electron.app"
DEST="$APP_NAME.app"
TMP=".$APP_NAME.app.building"

# Say what failed rather than stopping silently, and tidy up
trap 'echo "  ✗ Couldn'"'"'t build the Story Engine app (line $LINENO: $BASH_COMMAND)"; rm -rf "$TMP"' ERR

if [ ! -d "node_modules/electron" ]; then
  echo "  Electron isn't installed yet; skipping the Story Engine app."
  exit 0
fi

# npm can skip Electron's own download step; fetch it if it's missing
if [ ! -d "$SRC" ]; then
  echo "  Downloading Electron..."
  node node_modules/electron/install.js
fi

# An older checkout keeps a launcher app in git at the same path. Leave it be.
if git ls-files --error-unmatch "$DEST" >/dev/null 2>&1; then
  exit 0
fi

# Rebuild when Electron or this script changes
ELECTRON_VERSION=$(node -p "require('./node_modules/electron/package.json').version")
STAMP="$ELECTRON_VERSION $(shasum scripts/build-desktop-app.sh | cut -d' ' -f1)"
if [ "$(cat "$DEST/Contents/Resources/app/stamp" 2>/dev/null)" = "$STAMP" ]; then
  exit 0
fi

echo "  Building the Story Engine app..."
rm -rf "$TMP"
# -c makes a copy-on-write clone, which is instant on APFS
cp -Rc "$SRC" "$TMP" 2>/dev/null || cp -R "$SRC" "$TMP"

PLIST="$TMP/Contents/Info.plist"
plutil -replace CFBundleName -string "$APP_NAME" "$PLIST"
plutil -replace CFBundleDisplayName -string "$APP_NAME" "$PLIST"
plutil -replace CFBundleIdentifier -string "$BUNDLE_ID" "$PLIST"
cp electron/build-assets/AppIcon.icns "$TMP/Contents/Resources/electron.icns"

# Give the helper apps matching identifiers (com.github.Electron.helper → <id>.helper)
for HELPER_PLIST in "$TMP"/Contents/Frameworks/*Helper*.app/Contents/Info.plist; do
  [ -f "$HELPER_PLIST" ] || continue
  OLD_ID=$(plutil -extract CFBundleIdentifier raw "$HELPER_PLIST")
  plutil -replace CFBundleIdentifier -string "${OLD_ID/com.github.Electron/$BUNDLE_ID}" "$HELPER_PLIST"
done

# Swap Electron's demo app for a stub that runs electron/desktop.js from
# this folder, so code updates arrive with git and need no rebuild
rm -f "$TMP/Contents/Resources/default_app.asar"
mkdir -p "$TMP/Contents/Resources/app"
cat > "$TMP/Contents/Resources/app/package.json" <<JSON
{
  "name": "story-engine",
  "productName": "$APP_NAME",
  "main": "index.js",
  "private": true
}
JSON
cat > "$TMP/Contents/Resources/app/index.js" <<'JS'
// Generated by scripts/build-desktop-app.sh. Runs the Story Engine from
// the folder this app sits in.
const path = require("path");
const root = path.resolve(__dirname, "..", "..", "..", "..");
try {
  require(path.join(root, "electron", "desktop.js"));
} catch (err) {
  const { app, dialog } = require("electron");
  app.whenReady().then(() => {
    dialog.showErrorBox(
      "Story Engine can't start",
      "Keep the Story Engine app inside the harpoon-story-engine folder, " +
        "and put it in the Dock by dragging it from there.\n\n" + err.message,
    );
    app.exit(1);
  });
}
JS
echo "$STAMP" > "$TMP/Contents/Resources/app/stamp"

# Re-sign locally now the contents have changed
xattr -cr "$TMP" 2>/dev/null || true
if ! codesign --force --deep --sign - "$TMP"; then
  echo "  ⚠  Couldn't re-sign the Story Engine app; it may not open."
fi

rm -rf "$DEST"
mv "$TMP" "$DEST"
touch "$DEST"

# Tell macOS about the new name and icon
LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
[ -x "$LSREGISTER" ] && "$LSREGISTER" -f "$DEST" >/dev/null 2>&1 || true

echo "  ✓ Story Engine app ready"
